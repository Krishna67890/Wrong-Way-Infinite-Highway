export function createEmptyUpgrades(): CarUpgradeLevels {
  return {
    engine: 0,
    turbo: 0,
    tires: 0,
    handling: 0,
    brakes: 0,
    armor: 0,
    nitro: 0,
    repair: 0,
  };
}

export function getUpgradeCost(carPrice: number, currentLevel: number): number {
  const tierBase = Math.max(220, Math.round(carPrice * 0.035 + 260));
  return Math.round(tierBase * Math.pow(1.42, currentLevel));
}

export function getEffectiveCarStats(
  car: CarDefinition,
  levels?: Partial<CarUpgradeLevels>,
): CarStats {
  const upg = { ...createEmptyUpgrades(), ...(levels ?? {}) };
  return {
    topSpeed: Math.round(car.baseStats.topSpeed + upg.engine * 4.5),
    acceleration: Math.min(100, car.baseStats.acceleration + upg.turbo * 2.1),
    tireGrip: Math.min(100, car.baseStats.tireGrip + upg.tires * 2.0),
    handling: Math.min(100, car.baseStats.handling + upg.handling * 2.0),
    braking: Math.min(100, car.baseStats.braking + upg.brakes * 2.2),
    damageResistance: Math.min(0.55, car.baseStats.damageResistance + upg.armor * 0.015),
    nitroCapacity: Number((car.baseStats.nitroCapacity + upg.nitro * 0.35).toFixed(1)),
    repairEfficiency: Number((car.baseStats.repairEfficiency + upg.repair * 0.04).toFixed(2)),
  };
}

