export function xpRequiredForLevel(level: number): number {
  return 250 + (level - 1) * 180;
}

export function getCarById(id: string): CarDefinition {
  return CARS.find((c) => c.id === id) ?? CARS[0];
}

export function getWorldById(id: string): WorldDefinition {
  return WORLDS.find((w) => w.id === id) ?? WORLDS[0];
}

export function getModeById(id: string): GameModeDefinition {
  return GAME_MODES.find((m) => m.id === id) ?? GAME_MODES[0];
}

export function getBossById(id: BossType) {
  return BOSSES.find((b) => b.id === id) ?? BOSSES[0];
}
